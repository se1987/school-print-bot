DB_PATH = Path(os.getenv("DB_PATH", "school_prints.db"))
# PostgreSQL の接続文字列。設定されていれば SQLite の代わりに使う
DATABASE_URL = os.getenv("DATABASE_URL", "").strip()
# 既存の PostgreSQL に同居させるときのスキーマ名（未設定なら接続ロールの既定 = 通常 public）
DB_SCHEMA = os.getenv("DB_SCHEMA", "").strip()

