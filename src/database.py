"""
データベース操作モジュール
プリント情報・抽出タスク・子ども情報を管理する

バックエンドは環境変数で切り替わる:
- DATABASE_URL あり → PostgreSQL（Cloud Run などディスクが揮発する環境向け）
- DATABASE_URL なし → SQLite（DB_PATH のファイル。ローカル / Docker / Railway 向け）

SQL は両方で動く書き方に揃えてある（プレースホルダは ? で書き、PostgreSQL では %s に変換。
採番した id は RETURNING で受け取る。「今日」は SQL の date('now') ではなく JST の日付を
Python から渡す）。
"""

